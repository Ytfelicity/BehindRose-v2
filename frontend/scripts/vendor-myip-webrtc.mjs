    'webrtc.StatusError': '未取得映射候选',
    'webrtc.StatusUnavailable': 'WebRTC 不可用',
    'webrtc.NATType.host': 'host',
    'webrtc.NATType.srflx': 'srflx',
    'webrtc.NATType.prflx': 'prflx',
