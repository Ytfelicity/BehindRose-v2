  const timers = new Set();
  const setTimeout = (callback, milliseconds) => {
    let timer;
    timer = runtimeSetTimeout(() => { timers.delete(timer); callback(); }, milliseconds);
    timers.add(timer);
    return timer;
  };
  const clearTimeout = timer => { timers.delete(timer); runtimeClearTimeout(timer); };
  const activeConnections = new Set();
  const IPArray = { value: [] };
  // Country lookup remains the host application's separate operation. Returning
  // null avoids a MaxMind/network dependency and leaves the STUN sampler intact.
