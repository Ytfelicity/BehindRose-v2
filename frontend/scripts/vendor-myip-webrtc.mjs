function sliceBetween(start, end) {
  const begin = source.indexOf(start);
  const finish = source.indexOf(end, begin);
  if (begin < 0 || finish < begin) throw Error('Pinned MyIP WebRTC source block was not found: ' + start);
  return source.slice(begin, finish).trimEnd();
}

