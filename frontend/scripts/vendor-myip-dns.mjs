const hash = value => createHash('sha256').update(value).digest('hex');
async function source(relative) {
  const bytes = await readFile(path.join(root, relative));
  sourceHashes[relative] = hash(bytes);
  return bytes.toString('utf8');
}

// Preserve every upstream function body. Only static ES module import/export
// declarations are removed when nesting modules in separate lexical scopes.
function unwrapModule(value) {
  return value.replace(/^import .*;\r?\n/gm, '')
    .replace(/^export \{[^\n]*\} from .*;\r?\n/gm, '')
    .replace(/^export (?=(?:const|async function|function) )/gm, '');
}
function extractThrough(value, start, end) {
  const begin = value.indexOf(start);
  const finish = value.indexOf(end, begin);
  if (begin < 0 || finish < begin) throw Error('Pinned MyIP extraction marker missing: ' + start);
  return value.slice(begin, finish + end.length);
}

