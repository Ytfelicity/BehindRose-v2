import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { readFile } from 'node:fs/promises';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

const output = await build({ entryPoints: [fileURLToPath(new URL('../src/claude-handbook.tsx', import.meta.url))], bundle: true, write: false, platform: 'node', format: 'cjs', packages: 'external', jsx: 'automatic', logLevel: 'silent' });
const handbookSource = await readFile(new URL('../src/claude-handbook.tsx', import.meta.url), 'utf8');
assert.match(handbookSource, /anchor\.href = '\/claude-handbook-scripts\/' \+ item\.name/);
assert.match(handbookSource, /anchor\.download = item\.name/);
assert.doesNotMatch(handbookSource, /createObjectURL|revokeObjectURL|new Blob\(|blob:/, 'Desktop downloads use exact same-origin static script routes');
const requests = [];
let conflict = false;
const fetchFixture = async (url, options = {}) => {
  assert.ok(['/api/session', '/api/local'].includes(url), 'Only mocked local application routes are allowed');
  requests.push({ url, options });
  if (url === '/api/session') return { ok: true, json: async () => ({ ready: true, token: 'fixture' }) };
  return { ok: !conflict, json: async () => conflict ? { error: '时区已更改，请重新预览' } : { data: { echoed: JSON.parse(options.body) } } };
};
const module = { exports: {} };
const sandbox = { module, exports: module.exports, require: createRequire(import.meta.url), fetch: fetchFixture, AbortSignal, console };
vm.runInNewContext(output.outputFiles[0].text, sandbox, { filename: 'claude-handbook-fixture.cjs' });
const { ClaudeHandbook, HandbookMarkdown, claudeHandbookApi } = module.exports;
assert.equal(renderToStaticMarkup(React.createElement(ClaudeHandbook, { active: false })), '');
const markup = renderToStaticMarkup(React.createElement(ClaudeHandbook, { active: true }));
assert.equal(requests.length, 0, 'Opening or rendering the handbook must not inspect, mutate or test the network');
assert.equal((markup.match(/class="handbook-step-card"/g) ?? []).length, 13);
for (const number of Array.from({ length: 13 }, (_, n) => String(n + 1).padStart(2, '0'))) {
  assert.ok(markup.includes(`id="claude-handbook-step-${number}"`));
  assert.ok(markup.includes(`/claude-handbook.html#step-${number}`));
}
assert.equal((markup.match(/class="handbook-figure"/g) ?? []).length, 8, 'All original real figures are present');
assert.ok((markup.match(/<img[^>]*src="([^"]+)"/g) ?? []).every(image => image.includes('src="/claude-handbook-images/')), 'Every displayed image is an embedded local asset');
assert.match(markup, /官方 Claude 订阅主线/);
assert.match(markup, /只影响这个窗口及其后续启动的进程/);
assert.match(markup, /不对你的网络做任何测试/);
assert.match(markup, /不会修改 UTC 时钟/);
assert.match(markup, /手动勾选/);
assert.match(markup, /claude auth login/);
assert.doesNotMatch(markup, /预览一键配置|value="preserve"|备份并应用配置/, 'Persistent settings editor is not the primary article workflow');
assert.doesNotMatch(markup, /<input[^>]*checked=""/, 'No optional setting or checkpoint is selected by default');
assert.match(markup, /读取本机配置（不联网）/);
assert.match(markup, /读取工具箱已有恢复记录/);
assert.match(markup, /仅处理此前工具箱保存的 settings.json 备份/);
assert.equal((markup.match(/>下载脚本<\/button>/g) ?? []).length, 3);
const original = await readFile(new URL('../../docs/claude-handbook/handbook.md', import.meta.url), 'utf8');
const originalCommands = [...original.replace(/\r\n/g, '\n').matchAll(/^~~~[^\n]*\n([\s\S]*?)\n~~~\s*$/gm)].map(match => match[1]);
const decode = text => text.replace(/&quot;/g, '"').replace(/&#x27;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const renderedCommands = [...markup.matchAll(/<pre><code>([\s\S]*?)<\/code><\/pre>/g)].map(match => decode(match[1]));
assert.equal(originalCommands.length, 21);
assert.equal(renderedCommands.length, 24, 'Every original command plus all three downloadable scripts is rendered');
for (const command of originalCommands) assert.ok(renderedCommands.includes(command), 'Source command survives markdown rendering exactly: ' + command.slice(0, 40));
sandbox.document = { body: { dataset: { configBusy: 'true' } } };
const lockedMarkup = renderToStaticMarkup(React.createElement(ClaudeHandbook, { active: true }));
assert.match(lockedMarkup, /工具箱有配置操作正在进行/);
assert.match(lockedMarkup, /<button[^>]*disabled=""[^>]*>读取本机配置（不联网）/);
assert.match(lockedMarkup, /<button[^>]*disabled=""[^>]*>读取工具箱已有恢复记录/);
assert.equal(requests.length, 0, 'Opening the guide during ongoing work does not stop it or read config');
delete sandbox.document;

const sample = renderToStaticMarkup(React.createElement(HandbookMarkdown, { text: '## 标题\n\n**强调**与`$env:HTTP_PROXY`。\n\n| 项目 | 值 |\n| --- | --- |\n| A | <script>bad()</script> |\n\n~~~powershell\nWrite-Host "<test>"\n~~~\n\n[来源](https://example.invalid/docs)' }));
assert.match(sample, /<h3>标题<\/h3>/);
assert.match(sample, /<strong>强调<\/strong>/);
assert.match(sample, /<table>/);
assert.doesNotMatch(sample, /<script>/);
assert.match(sample, /&lt;script&gt;bad\(\)&lt;\/script&gt;/);
assert.match(sample, /Write-Host &quot;&lt;test&gt;&quot;/);
assert.match(sample, /href="https:\/\/example.invalid\/docs"/);

const status = await claudeHandbookApi('claude-timezone-inspect');
assert.equal(status.echoed.command, 'claude-timezone-inspect');
await claudeHandbookApi('claude-timezone-plan');
assert.deepEqual(JSON.parse(requests.at(-1).options.body), { command: 'claude-timezone-plan' });
await claudeHandbookApi('claude-timezone-apply', { planId: 'fixture-plan' });
assert.deepEqual(JSON.parse(requests.at(-1).options.body), { command: 'claude-timezone-apply', planId: 'fixture-plan' });
const beforeForbidden = requests.length;
for (const command of ['quality-start', 'claude-plan', 'claude-apply', 'claude-auth-login', 'run-script']) await assert.rejects(() => claudeHandbookApi(command), /手册不支持/);
assert.equal(requests.length, beforeForbidden, 'Network tests, permanent proxy writes, login and script execution are absent from this bridge');
conflict = true;
await assert.rejects(() => claudeHandbookApi('claude-timezone-restore', { planId: 'fixture-restore' }), /时区已更改/);
assert.equal(requests.length, beforeForbidden + 2, 'A failed mutation is not retried');
console.log('PASS: 13 article sections, 8 local real figures, safe markdown, process-only guide, optional settings unchecked, manual local reads, display/download-only commands and allowlisted mocked timezone API. No browser, real API, network or settings access.');
